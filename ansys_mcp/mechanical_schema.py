"""Versioned, backend-neutral Mechanical recipe contract.

The product dispatcher deliberately accepts only this public operation vocabulary.
Raw product Python is available through an explicit trusted file, never eval paths.
"""
from __future__ import annotations

import math
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class MechanicalStrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class MechanicalSessionSpec(MechanicalStrictModel):
    action: Literal["new", "reuse", "summary", "close"] = "new"
    id: str | None = Field(default=None, min_length=1, max_length=128)

    @model_validator(mode="after")
    def existing_session_has_id(self) -> "MechanicalSessionSpec":
        if self.action != "new" and not self.id:
            raise ValueError("An existing Mechanical session requires its id.")
        if self.action == "new" and self.id:
            raise ValueError("New Mechanical session ids are generated by the server.")
        return self


class MechanicalLaunchSpec(MechanicalStrictModel):
    show_gui: bool = False
    product_version: str | None = Field(default=None, pattern=r"^[0-9]{3}$")
    elevation: Literal["auto", "never", "require"] = "auto"


class MechanicalProjectSpec(MechanicalStrictModel):
    open_path: str | None = None
    save_path: str | None = None
    overwrite: bool = False
    system_name: str | None = None
    template_name: str = "Static Structural (ANSYS)"
    solver: str | None = None
    geometry_path: str | None = None


class MechanicalOperation(MechanicalStrictModel):
    op: Literal[
        "discover", "inspect", "find", "get", "set", "call", "construct",
        "script", "project_open", "project_save", "project_reopen",
        "engineering_data",
    ]
    id: str | None = Field(default=None, pattern=r"^[A-Za-z][A-Za-z0-9_-]{0,63}$")
    target: str | dict[str, Any] = "Model"
    member: str | None = Field(default=None, pattern=r"^[A-Za-z][A-Za-z0-9_]*$")
    args: list[Any] = Field(default_factory=list)
    kwargs: dict[str, Any] = Field(default_factory=dict)
    value: Any = None
    store_as: str | None = Field(default=None, pattern=r"^[A-Za-z][A-Za-z0-9_]*$")
    overload: list[str] | None = None
    name: str | None = None
    category: Any = None
    recursive: bool = True
    limit: int = Field(default=200, ge=1, le=10000)
    path: str | None = None
    system_name: str | None = None
    overwrite: bool = False
    script_path: str | None = None
    result_name: str = Field(default="mcp_result", pattern=r"^[A-Za-z][A-Za-z0-9_]*$")
    invalidate_refs: bool = False
    # Engineering Data is dispatched in the owning Workbench session, separately.
    action: Literal["inspect", "get", "set", "call", "script"] | None = None

    @model_validator(mode="after")
    def valid_operation(self) -> "MechanicalOperation":
        if self.op in {"get", "set", "call"} and not self.member:
            raise ValueError(f"{self.op} requires member.")
        if self.op == "script" and not self.script_path:
            raise ValueError("script requires a trusted script_path.")
        if self.op in {"project_open", "project_save"} and not self.path:
            raise ValueError(f"{self.op} requires path.")
        if self.op == "find" and self.name is None and self.category is None:
            raise ValueError("find requires name or category.")
        if self.op == "engineering_data":
            if self.action is None:
                raise ValueError("engineering_data requires action.")
            if self.action in {"get", "set", "call"} and not self.member:
                raise ValueError("Engineering Data get/set/call requires member.")
            if self.action == "script" and not self.script_path:
                raise ValueError("Engineering Data script requires script_path.")
        _validate_value(self.target)
        _validate_value(self.value)
        _validate_value(self.args)
        _validate_value(self.kwargs)
        _validate_value(self.category)
        for name in self.kwargs:
            _public_identifier(name)
        for path in self.overload or []:
            _public_type_path(path)
        if isinstance(self.target, str):
            (_public_type_path if self.op == "construct" else _public_path)(self.target)
        return self


class MechanicalRecipe(MechanicalStrictModel):
    model_config = ConfigDict(extra="forbid", json_schema_extra={
        "x-mechanical-value-protocol": {
            "quantity": {"$type": "quantity", "value": "finite number", "unit": "explicit unit string"},
            "quantity_series": {"$type": "quantity_series", "values": "finite number array", "unit": "explicit unit string"},
            "enum": {"$type": "enum", "type": "public qualified enum type", "name": "public member name (optional with value)", "value": "integer value (optional with name)"},
            "ref": {"$type": "ref", "session_id": "session identity", "generation": "nonnegative integer", "object_id": "opaque object identity", "namespace": "mechanical or engineering_data"},
            "local_ref": {"$type": "local_ref", "name": "prior store_as name", "index": "optional nonnegative collection index"},
            "selection": {"$type": "selection", "kind": "SelectionTypeEnum public member", "ids": "nonnegative integer array"},
            "table": {"$type": "table", "columns": "array of {name, unit?}", "rows": "rectangular array; creates System.Data.DataTable"},
            "path": {"$type": "path", "path": "allowed-root relative or absolute path", "role": "input or output", "kind": "file (default) or directory"},
            "clr_types": "Public qualified type names support [], &, and nested generic arguments such as System.Collections.Generic.List[System.Double].",
        },
    })
    version: Literal["1"] = "1"
    backend: Literal["workbench", "pymechanical"] = "workbench"
    mode: Literal["persistent", "batch"] = "persistent"
    session: MechanicalSessionSpec = Field(default_factory=MechanicalSessionSpec)
    launch: MechanicalLaunchSpec = Field(default_factory=MechanicalLaunchSpec)
    project: MechanicalProjectSpec = Field(default_factory=MechanicalProjectSpec)
    operations: list[MechanicalOperation] = Field(default_factory=list)
    max_inline_bytes: int = Field(default=262144, ge=1024, le=8388608)

    @model_validator(mode="after")
    def recipe_contract(self) -> "MechanicalRecipe":
        if self.session.action in {"close", "summary"} and self.operations:
            raise ValueError("Session close/summary cannot include product operations.")
        if self.session.action == "reuse" and (self.project.open_path or self.project.geometry_path):
            raise ValueError("Reuse uses the existing project; use project_open explicitly to replace it.")
        ids: set[str] = set()
        for index, operation in enumerate(self.operations):
            operation_id = operation.id or f"operation_{index + 1}"
            if operation_id in ids:
                raise ValueError(f"Duplicate Mechanical operation id: {operation_id}")
            ids.add(operation_id)
        if self.backend == "pymechanical" and any(op.op == "engineering_data" for op in self.operations):
            raise ValueError("Engineering Data requires the Workbench backend.")
        return self


def _public_identifier(value: str) -> None:
    if not isinstance(value, str) or not value or value.startswith("_") or not value.isidentifier():
        raise ValueError("API members must be public identifiers.")


def _public_path(value: str) -> None:
    if not isinstance(value, str):
        raise ValueError("API paths must be strings.")
    for part in value.split("."):
        _public_identifier(part)


def _public_type_path(value: str) -> None:
    if value.endswith("[]") or value.endswith("&"):
        _public_type_path(value[:-2] if value.endswith("[]") else value[:-1])
        return
    if "[" not in value:
        _public_path(value)
        return
    base, arguments = value.split("[", 1)
    _public_path(base)
    if not arguments.endswith("]"):
        raise ValueError("Invalid CLR generic type descriptor.")
    depth, start = 0, 0
    parts = []
    arguments = arguments[:-1]
    for index, character in enumerate(arguments):
        if character == "[":
            depth += 1
        elif character == "]":
            depth -= 1
        elif character == "," and depth == 0:
            parts.append(arguments[start:index].strip())
            start = index + 1
        if depth < 0:
            raise ValueError("Invalid CLR generic type descriptor.")
    if depth != 0:
        raise ValueError("Invalid CLR generic type descriptor.")
    parts.append(arguments[start:].strip())
    for part in parts:
        _public_type_path(part)


def _validate_value(value: Any) -> None:
    """Validate the typed value boundary without importing a product runtime."""
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError("Mechanical numbers must be finite.")
    if isinstance(value, list):
        for item in value:
            _validate_value(item)
    elif isinstance(value, dict):
        marker = value.get("$type")
        required = {
            "quantity": {"value", "unit"}, "quantity_series": {"values", "unit"},
            "enum": {"type"}, "ref": {"session_id", "generation", "object_id"},
            "selection": {"kind", "ids"}, "table": {"columns", "rows"},
            "path": {"path", "role"}, "local_ref": {"name"},
        }
        if marker:
            if not isinstance(marker, str):
                raise ValueError("Typed value markers must be strings.")
            if marker not in required or not required[marker].issubset(value):
                raise ValueError("Invalid Mechanical typed value.")
            if marker == "ref" and (type(value["generation"]) is not int or value["generation"] < 0):
                raise ValueError("Reference generation must be a nonnegative integer.")
            if marker == "ref" and any(not isinstance(value[key], str) or not value[key] for key in ("session_id", "object_id")):
                raise ValueError("References require nonempty string identities.")
            if marker == "ref" and value.get("namespace", "mechanical") not in ("mechanical", "engineering_data"):
                raise ValueError("Object reference namespace is not supported.")
            if marker in {"quantity", "quantity_series"}:
                if not isinstance(value["unit"], str) or not value["unit"]:
                    raise ValueError("Quantities require an explicit nonempty unit.")
                numbers = value.get("values") if marker == "quantity_series" else [value["value"]]
                if not isinstance(numbers, list) or any(type(item) not in {int, float} for item in numbers):
                    raise ValueError("Quantity values must be numeric.")
            if marker == "enum":
                _public_path(value["type"])
                if "value" in value:
                    if type(value["value"]) is not int:
                        raise ValueError("Numeric enum values must be integers.")
                elif "name" in value:
                    _public_identifier(value["name"])
                else:
                    raise ValueError("Enums require a public name or numeric value.")
            if marker == "path" and (not isinstance(value["role"], str) or value["role"] not in {"input", "output"}):
                raise ValueError("Typed path role must be input or output.")
            if marker == "path" and (not isinstance(value["path"], str) or not value["path"]):
                raise ValueError("Typed paths require a nonempty path string.")
            if marker == "path" and (not isinstance(value.get("kind", "file"), str) or value.get("kind", "file") not in {"file", "directory"}):
                raise ValueError("Typed path kind must be file or directory.")
            if marker == "local_ref":
                _public_identifier(value["name"])
                if "index" in value and (type(value["index"]) is not int or value["index"] < 0):
                    raise ValueError("Collection reference indices must be nonnegative integers.")
            if marker == "table":
                columns = value["columns"]
                if not isinstance(columns, list) or not columns or any(not isinstance(c, dict) or "name" not in c for c in columns):
                    raise ValueError("Tables require named columns.")
                if not isinstance(value["rows"], list) or any(not isinstance(row, list) or len(row) != len(columns) for row in value["rows"]):
                    raise ValueError("Table rows must match the columns.")
            if marker == "selection" and (not isinstance(value["ids"], list) or any(type(i) is not int or i < 0 for i in value["ids"])):
                raise ValueError("Selection ids must be nonnegative integers.")
            if marker == "selection":
                _public_identifier(value["kind"])
        for child in value.values():
            _validate_value(child)


